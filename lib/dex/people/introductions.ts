 const cues=new Set<Cue>();
 for(const m of matches){const next=matches.find(n=>n.start>=m.end)?.start??source.length;
 const after=source.slice(m.end,Math.min(next,m.end+35)).split(/[,.!?;\n]|지만|는데|반면/)[0];
 const before=source.slice(Math.max(0,m.start-10),m.start);
 if(/(?:안|못)\s*(?:(?:마시|먹|하|즐기|좋아하)는\s*)?$/.test(before)||/(?:안|못)\s*(?:마|먹|하|해|한|했|할|가|갔|와|오|좋아|즐|함|감|옴)|(?:지|진)\s*(?:않|못)|싫|끊|않|아니|없|대신|말고|보다는|별로|안\s*$|못\s*$/.test(after))continue;
 cues.add(m.cue);
 }
